#!/usr/bin/env bash
# Pull the approved icon set in from the canonical workspace.
#
# icons/ used to be a symlink to ~/Desktop/Design Sorcery/icons. That kept a
# single source of truth but meant the repo only built on one machine: a clone
# has no target, and Vercel failed with
#   ENOENT: no such file or directory, stat '/vercel/path0/icons'
#
# So the files are vendored, and this regenerates them. Design Sorcery stays
# the source of truth. Never hand-edit anything in icons/; change it there and
# run this.
set -euo pipefail

SRC="${DESIGN_SORCERY:-$HOME/Desktop/Design Sorcery}/icons"
DEST="$(cd "$(dirname "$0")/.." && pwd)/icons"

if [ ! -d "$SRC" ]; then
  echo "Canonical icon set not found at: $SRC" >&2
  echo "Set DESIGN_SORCERY to its parent folder, or clone it there." >&2
  exit 1
fi

mkdir -p "$DEST"
for f in "$SRC"/*.ts; do
  name="$(basename "$f")"
  {
    echo "// Generated by scripts/sync-icons.sh. Do not edit."
    echo "// Source of truth: Design Sorcery/icons/$name"
    echo
    cat "$f"
  } > "$DEST/$name"
done

echo "Synced $(ls -1 "$DEST"/*.ts | wc -l | tr -d ' ') icon files from $SRC"
